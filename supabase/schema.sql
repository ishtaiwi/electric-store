DO $$
DECLARE
  t TEXT;
BEGIN
  FOREACH t IN ARRAY ARRAY[
    'users','suppliers','customers','product_brands','product_categories','products','invoices','sales',
    'customer_payments','discounts','inventory_adjustments','cancelled_sales',
    'expenses','additional_income','budget','store_settings','price_lists',
    'price_list_items','supplier_attachments','supplier_invoices',
    'supplier_payments','audit_logs','mobile_trial_invoices','mobile_trial_sales'
  ]
  LOOP
    EXECUTE format('DROP POLICY IF EXISTS "allow_all_anon_%s" ON %I', t, t);
    EXECUTE format(
      'CREATE POLICY "allow_all_anon_%s" ON %I FOR ALL TO anon, authenticated USING (true) WITH CHECK (true)',
      t, t
    );
  END LOOP;
END $$;

-- Grant access
